#!/bin/sh
# One-time dev-host setup for direct ota-lab (250, 205, ...). Run as normal user.
set -eu

SCRIPT=$(readlink -f "$0" 2>/dev/null || echo "$0")
SCRIPT_DIR=$(CDPATH= cd "$(dirname "$SCRIPT")" && pwd)
GK1221_ROOT=$(CDPATH= cd "$SCRIPT_DIR/../.." && pwd)

REL_HOST=${REL_HOST:-}
REL_SIGN_KEY=${REL_SIGN_KEY:-}
LAB_SUBNET=${LAB_SUBNET:-192.168.1.0/24}
NFS_EXPORT_ROOT=
OTA_WORK_ROOT=
SIGN_KEY=${SIGN_KEY:-$HOME/1221/ota_key.pem}
SKIP_APT=0
DRY_RUN=0

EXPORT_TAG="# ota-lab-export"
EXPORT_OPTS="insecure,rw,sync,no_subtree_check,no_root_squash"

log() { echo "[ota-dev-setup] $*"; }
die() { echo "[ota-dev-setup] ERROR: $*" >&2; exit 1; }

usage() {
    echo "Usage: $0 [--export-root DIR] [--work-root DIR] [--sign-key PATH]" >&2
    echo "       [--rel-host user@216] [--lab-subnet CIDR] [--skip-apt] [--dry-run]" >&2
    echo "  Run once on each new dev machine inside gk1221 (board/ota_ab/ota-dev-setup.sh)." >&2
    exit 2
}

pick_lab_ip() {
    ip -4 addr show scope global 2>/dev/null | awk '/inet 192\.168\.1\./ { split($2, a, "/"); print a[1]; exit }'
}

run_root() {
    if [ "$(id -u)" -eq 0 ]; then
        "$@"
    elif command -v sudo >/dev/null 2>&1; then
        sudo "$@"
    else
        die "need root or sudo for: $*"
    fi
}

while [ "$#" -gt 0 ]; do
    case "$1" in
        --export-root)
            [ "$#" -ge 2 ] || usage
            NFS_EXPORT_ROOT=$2
            shift 2
            ;;
        --work-root)
            [ "$#" -ge 2 ] || usage
            OTA_WORK_ROOT=$2
            shift 2
            ;;
        --sign-key)
            [ "$#" -ge 2 ] || usage
            SIGN_KEY=$2
            shift 2
            ;;
        --rel-host)
            [ "$#" -ge 2 ] || usage
            REL_HOST=$2
            shift 2
            ;;
        --lab-subnet)
            [ "$#" -ge 2 ] || usage
            LAB_SUBNET=$2
            shift 2
            ;;
        --skip-apt) SKIP_APT=1; shift ;;
        --dry-run) DRY_RUN=1; shift ;;
        -h|--help) usage ;;
        *) die "unknown option: $1" ;;
    esac
done

[ -f "$GK1221_ROOT/provenance.json" ] || die "not an APP-OTA standalone tree"
[ "$(id -u)" -eq 0 ] && die "do not run as root; use normal user (ps) and sudo only when needed"

if [ -z "$NFS_EXPORT_ROOT" ]; then
    NFS_EXPORT_ROOT=$(df --output=target "$GK1221_ROOT" 2>/dev/null | tail -1)
    [ -n "$NFS_EXPORT_ROOT" ] || NFS_EXPORT_ROOT=$HOME
fi
[ -z "$OTA_WORK_ROOT" ] && OTA_WORK_ROOT="$NFS_EXPORT_ROOT/ota-lab-work"

case "$OTA_WORK_ROOT" in
    "$NFS_EXPORT_ROOT"/*) ;;
    *) die "OTA_WORK_ROOT must be under NFS_EXPORT_ROOT ($NFS_EXPORT_ROOT)" ;;
esac

NFS_SERVER=$(pick_lab_ip)
[ -n "$NFS_SERVER" ] || die "no 192.168.1.x address found on this host"

log "gk1221 root     : $GK1221_ROOT"
log "nfs server ip   : $NFS_SERVER"
log "nfs export root : $NFS_EXPORT_ROOT"
log "ota work root   : $OTA_WORK_ROOT"
log "sign key        : $SIGN_KEY"

if [ "$DRY_RUN" = 1 ]; then
    log "dry-run only; no changes made"
    exit 0
fi

if [ "$SKIP_APT" != 1 ] && command -v apt-get >/dev/null 2>&1; then
    log "installing packages (nfs-kernel-server python3 openssl rsync openssh-client)..."
    run_root apt-get update -qq
    run_root apt-get install -y nfs-kernel-server python3 openssl rsync openssh-client
fi

mkdir -p "$OTA_WORK_ROOT/.lab-push" "$(dirname "$SIGN_KEY")"
chmod 700 "$(dirname "$SIGN_KEY")"

[ -s "$SIGN_KEY" ] || die "provide an existing external signing key via --sign-key; keys are never fetched automatically"
chmod 600 "$SIGN_KEY"
[ -s "$SIGN_KEY" ] || die "SIGN_KEY missing: $SIGN_KEY"

LOCAL_CONF=$SCRIPT_DIR/devices.local.conf
cat > "$LOCAL_CONF" <<EOF
# Generated by ota-dev-setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
NFS_SERVER=$NFS_SERVER
NFS_EXPORT_ROOT=$NFS_EXPORT_ROOT
OTA_WORK_ROOT=$OTA_WORK_ROOT
SIGN_KEY=$SIGN_KEY
EOF
chmod 600 "$LOCAL_CONF"
log "wrote $LOCAL_CONF"

EXPORT_LINE="$NFS_EXPORT_ROOT $LAB_SUBNET($EXPORT_OPTS)"
EXPORT_FILE=/etc/exports
if run_root grep -q "^$NFS_EXPORT_ROOT " "$EXPORT_FILE" 2>/dev/null; then
    log "updating existing NFS export (ensure insecure is set)..."
    run_root sed -i "s|^$NFS_EXPORT_ROOT .*|$EXPORT_LINE $EXPORT_TAG|" "$EXPORT_FILE"
else
    log "adding NFS export to $EXPORT_FILE"
    printf '%s %s\n' "$EXPORT_LINE" "$EXPORT_TAG" | run_root tee -a "$EXPORT_FILE" >/dev/null
fi

log "applying NFS exports..."
run_root exportfs -ra 2>/dev/null || run_root exportfs -r
run_root systemctl enable nfs-kernel-server 2>/dev/null || true
run_root systemctl restart nfs-kernel-server 2>/dev/null || true

BASHRC=$HOME/.bashrc
MARKER="# ota-lab dev path"
if ! grep -qF "$MARKER" "$BASHRC" 2>/dev/null; then
    cat >> "$BASHRC" <<EOF

$MARKER
export GK1221_ROOT=$GK1221_ROOT
export PATH="\$GK1221_ROOT/compat/lab:\$PATH"
EOF
    log "appended PATH to $BASHRC"
fi

log "verify:"
log "  showmount -e localhost | grep $NFS_EXPORT_ROOT"
showmount -e localhost 2>/dev/null | grep "$NFS_EXPORT_ROOT" || log "WARNING: export not visible yet"
log "SUCCESS: dev host ready. Run:"
log "  cd $GK1221_ROOT"
log "  ./compat/lab/ota-lab.sh --source /path/to/deploy --board BOARD_IP --version Vx.y.z"
